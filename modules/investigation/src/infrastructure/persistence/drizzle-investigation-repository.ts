import { and, asc, eq, sql, type SQL } from 'drizzle-orm';
import {
  executorOf,
  pgErrorCode,
  type PersistenceHandle,
  type TransactionContext,
} from '@sdris/database';
import {
  createEntityRef,
  createError,
  err,
  ok,
  parseEntityId,
  timestampFromDate,
  type Result,
} from '@sdris/shared-kernel';
import {
  LINK_ROLES,
  type CaseTestAttemptLink,
  type InvestigationCase,
  type InvestigationCaseId,
  type LinkRole,
  type NewCaseTestAttemptLink,
  type NewInvestigationCase,
} from '../../domain/investigation-case';
import {
  parseTestStage,
  type NewTestAttempt,
  type TestAttempt,
  type TestAttemptId,
} from '../../domain/test-attempt';
import type { NewUut, Uut, UutId, UutRef } from '../../domain/uut';
import type {
  InvestigationRepository,
  RepositoryError,
} from '../../application/ports/investigation-repository';
import type { TransactionToken } from '../../application/ports/transaction-scope';
import { caseTestAttemptLink, investigationCase, testAttempt, uut as uutTable } from './schema';

const PG_FOREIGN_KEY_VIOLATION = '23503';
/** The two composite foreign keys that make a link's UUT equal to its case's and its attempt's UUT. */
const SAME_UUT_CONSTRAINTS: readonly string[] = [
  'case_test_attempt_link_case_uut_fkey',
  'case_test_attempt_link_attempt_uut_fkey',
];

/** Name of the violated constraint, looking through wrapped driver errors (Drizzle wraps them in `cause`). */
function pgConstraintName(error: unknown): string | undefined {
  let current: unknown = error;
  for (let depth = 0; depth < 5 && current && typeof current === 'object'; depth += 1) {
    const name = (current as { constraint?: unknown }).constraint;
    if (typeof name === 'string') return name;
    current = (current as { cause?: unknown }).cause;
  }
  return undefined;
}

/** Unwraps a Result that can only fail if stored data is corrupt, which is a bug, not a domain outcome. */
function stored<T>(result: Result<T, { message: string }>, what: string): T {
  if (!result.ok) throw new Error(`Corrupt ${what} in storage: ${result.error.message}`);
  return result.value;
}

function uutRef(id: string): UutRef {
  const parsed = stored(parseEntityId<'UUT'>(id, 'uut_id'), 'uut_id');
  return stored(createEntityRef('UUT', parsed), 'uut reference');
}

/**
 * Retrieval order of roles (Owner decision Q9), expressed in SQL so the database orders the rows. Built from
 * constants only, never from input.
 */
const roleOrder: SQL = sql`case ${caseTestAttemptLink.role} ${sql.join(
  LINK_ROLES.map((role, index) => sql`when ${role} then ${sql.raw(String(index))}`),
  sql` `,
)} end`;

function toUut(row: typeof uutTable.$inferSelect): Uut {
  return Object.freeze({
    id: stored(parseEntityId<'UUT'>(row.id, 'id'), 'uut id'),
    ...(row.serialNumber === null ? {} : { serialNumber: row.serialNumber }),
    ...(row.hostname === null ? {} : { hostname: row.hostname }),
    createdAt: stored(timestampFromDate(row.createdAt, 'created_at'), 'created_at'),
  });
}

function toTestAttempt(row: typeof testAttempt.$inferSelect): TestAttempt {
  return Object.freeze({
    id: stored(parseEntityId<'TestAttempt'>(row.id, 'id'), 'attempt id'),
    uut: uutRef(row.uutId),
    stage: stored(parseTestStage(row.stage), 'stage'),
    ...(row.externalExecutionReference === null
      ? {}
      : { externalExecutionReference: row.externalExecutionReference }),
    registeredAt: stored(timestampFromDate(row.registeredAt, 'registered_at'), 'registered_at'),
  });
}

function toLink(
  caseId: InvestigationCaseId,
  row: typeof caseTestAttemptLink.$inferSelect,
): CaseTestAttemptLink {
  return Object.freeze({
    caseId,
    attemptId: stored(parseEntityId<'TestAttempt'>(row.attemptId, 'attempt_id'), 'attempt id'),
    uut: uutRef(row.uutId),
    role: row.role as LinkRole,
    linkedAt: stored(timestampFromDate(row.linkedAt, 'linked_at'), 'linked_at'),
  });
}

/**
 * PostgreSQL adapter for the Investigation repository port. Drizzle never leaves this file. Every timestamp is
 * generated by the database (`default now()`); this adapter never writes `created_at`, `registered_at`, `opened_at`
 * or `linked_at`, so no caller can choose them.
 */
export class DrizzleInvestigationRepository implements InvestigationRepository {
  constructor(private readonly persistence: PersistenceHandle) {}

  private executor(tx?: TransactionToken) {
    return executorOf(this.persistence, tx as unknown as TransactionContext | undefined);
  }

  async addUut(entity: NewUut, tx: TransactionToken): Promise<Result<Uut, RepositoryError>> {
    const [row] = await this.executor(tx)
      .insert(uutTable)
      .values({
        id: entity.id,
        serialNumber: entity.serialNumber ?? null,
        hostname: entity.hostname ?? null,
      })
      .onConflictDoNothing({ target: uutTable.id })
      .returning();
    return row
      ? ok(toUut(row))
      : err(
          createError({
            code: 'investigation.uut_already_exists' as const,
            message: 'A UUT with this id already exists.',
          }),
        );
  }

  async getUut(id: UutId, tx?: TransactionToken): Promise<Uut | undefined> {
    const [row] = await this.executor(tx).select().from(uutTable).where(eq(uutTable.id, id));
    return row ? toUut(row) : undefined;
  }

  async addTestAttempt(
    entity: NewTestAttempt,
    tx: TransactionToken,
  ): Promise<Result<TestAttempt, RepositoryError>> {
    const [row] = await this.executor(tx)
      .insert(testAttempt)
      .values({
        id: entity.id,
        uutId: entity.uut.id,
        stage: entity.stage,
        externalExecutionReference: entity.externalExecutionReference ?? null,
      })
      .onConflictDoNothing({ target: testAttempt.id })
      .returning();
    return row
      ? ok(toTestAttempt(row))
      : err(
          createError({
            code: 'investigation.attempt_already_exists' as const,
            message: 'A test attempt with this id already exists.',
          }),
        );
  }

  async getTestAttempt(id: TestAttemptId, tx?: TransactionToken): Promise<TestAttempt | undefined> {
    const [row] = await this.executor(tx).select().from(testAttempt).where(eq(testAttempt.id, id));
    return row ? toTestAttempt(row) : undefined;
  }

  async add(
    created: NewInvestigationCase,
    tx: TransactionToken,
  ): Promise<Result<InvestigationCase, RepositoryError>> {
    const [row] = await this.executor(tx)
      .insert(investigationCase)
      .values({ id: created.id, uutId: created.uut.id, version: 1 })
      .onConflictDoNothing({ target: investigationCase.id })
      .returning();
    if (!row) {
      return err(
        createError({
          code: 'investigation.case_already_exists' as const,
          message: 'A case with this id already exists.',
        }),
      );
    }
    return ok(
      Object.freeze({
        id: created.id,
        uut: created.uut,
        openedAt: stored(timestampFromDate(row.openedAt, 'opened_at'), 'opened_at'),
        version: row.version,
        links: Object.freeze([]),
      }),
    );
  }

  async get(
    id: InvestigationCaseId,
    tx?: TransactionToken,
  ): Promise<InvestigationCase | undefined> {
    // ONE statement, so the version and the links come from the same snapshot. Two separate SELECTs would let a
    // concurrent commit slip in between under READ COMMITTED and produce a state that never existed (a stale
    // version with newer links).
    const rows = await this.executor(tx)
      .select({ case: investigationCase, link: caseTestAttemptLink })
      .from(investigationCase)
      .leftJoin(caseTestAttemptLink, eq(caseTestAttemptLink.caseId, investigationCase.id))
      .leftJoin(testAttempt, eq(caseTestAttemptLink.attemptId, testAttempt.id))
      .where(eq(investigationCase.id, id))
      // Explicit and total: never rely on implicit row order (Owner decisions Q9 and the clarification addendum E).
      .orderBy(asc(testAttempt.registeredAt), asc(caseTestAttemptLink.attemptId), roleOrder);
    const row = rows[0]?.case;
    if (!row) return undefined;
    const caseId = stored(parseEntityId<'InvestigationCase'>(row.id, 'id'), 'case id');
    return Object.freeze({
      id: caseId,
      uut: uutRef(row.uutId),
      openedAt: stored(timestampFromDate(row.openedAt, 'opened_at'), 'opened_at'),
      version: row.version,
      links: Object.freeze(rows.flatMap((r) => (r.link ? [toLink(caseId, r.link)] : []))),
    });
  }

  async addLink(
    current: InvestigationCase,
    link: NewCaseTestAttemptLink,
    tx: TransactionToken,
  ): Promise<
    Result<{ readonly version: number; readonly link: CaseTestAttemptLink }, RepositoryError>
  > {
    const executor = this.executor(tx);
    // Optimistic concurrency: one atomic UPDATE; only the writer that still holds the stored version advances it.
    const [bumped] = await executor
      .update(investigationCase)
      .set({ version: sql`${investigationCase.version} + 1` })
      .where(
        and(eq(investigationCase.id, current.id), eq(investigationCase.version, current.version)),
      )
      .returning({ version: investigationCase.version });
    if (!bumped) {
      return err(
        createError({
          code: 'investigation.concurrency_conflict' as const,
          message: 'The case was changed by someone else (or does not exist); reload and retry.',
          details: { expectedVersion: current.version },
        }),
      );
    }
    try {
      const [row] = await executor
        .insert(caseTestAttemptLink)
        .values({
          caseId: link.caseId,
          attemptId: link.attemptId,
          uutId: link.uut.id,
          role: link.role,
        })
        .returning();
      return ok({ version: bumped.version, link: toLink(current.id, row!) });
    } catch (error) {
      // Only the same-UUT keys mean "mismatch". Any other failure (a unique violation from a racing writer, a
      // check, a trigger, a lost connection) is NOT translated and not suppressed: it is thrown, which rolls the
      // transaction back together with the version bump.
      if (
        pgErrorCode(error) === PG_FOREIGN_KEY_VIOLATION &&
        SAME_UUT_CONSTRAINTS.includes(pgConstraintName(error) ?? '')
      ) {
        return err(
          createError({
            code: 'investigation.uut_mismatch' as const,
            message: 'A link names a different UUT than its case or attempt; storage refused it.',
          }),
        );
      }
      throw error;
    }
  }
}
